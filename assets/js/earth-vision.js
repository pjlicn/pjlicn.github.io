function createSurfaceQuaternion(normal) {
  const localUp = new THREE.Vector3(0, 1, 0).addScaledVector(normal, -normal.y);
  if (localUp.lengthSq() < 0.001) localUp.set(0, 0, 1);
  localUp.normalize();
  const localRight = new THREE.Vector3().crossVectors(localUp, normal).normalize();
  const basis = new THREE.Matrix4().makeBasis(localRight, localUp, normal);
  return new THREE.Quaternion().setFromRotationMatrix(basis);
}

