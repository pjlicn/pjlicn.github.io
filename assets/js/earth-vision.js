function formatSignedIndex(value) {
  return `${value >= 0 ? "+" : ""}${value.toFixed(2)}`;
}

function renderSyntheticObservationSamples(group, config, variable) {
  if (!group) return;
  group.replaceChildren();
  const variableIndex = Object.keys(WATER_VARIABLE_LABELS).indexOf(variable);
  const regionIndex = WATER_REGION_CONFIGS.findIndex((item) => item.id === config.id);
  const interval = [23, 17, 29, 25][variableIndex] || 21;
  const offset = 7 + regionIndex * 4 + variableIndex * 3;
  for (let day = offset; day < 365; day += interval + ((day + regionIndex) % 3)) {
    const value = calculateWaterState(config, day)[variable] + calculateObservationOffset(config, day, variable);
    const circle = document.createElementNS(SVG_NAMESPACE, "circle");
    circle.setAttribute("cx", chartX(day).toFixed(2));
    circle.setAttribute("cy", chartY(value).toFixed(2));
    circle.setAttribute("r", "1.7");
    group.append(circle);
  }
}

