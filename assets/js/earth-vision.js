function updateRegionalIntegration(details, observationPhase, animate, scale, step) {
  details.byRegion.forEach((detail) => {
    detail.regionalIntegration.pulses.forEach((item) => {
      const progress = animate && step === "integrate"
        ? (observationPhase * 5 + item.phase) % 1
        : item.phase;
      item.pulse.position.copy(item.curve.getPoint(progress));
    });
    if (detail.regionalIntegration.group.visible) {
      const pulseScale = step === "integrate" && animate ? 1 + Math.sin(observationPhase * Math.PI * 8) * 0.14 : 1;
      detail.regionalIntegration.halo.scale.setScalar(pulseScale);
    }
  });
  if (scale === "global") return;
}

function updateModelOutputLink(link, selectedRegion, observationPhase, step) {
  if (!link || step !== "inform") return;
  const start = selectedRegion.position.clone().normalize().multiplyScalar(2.08);
  const outward = selectedRegion.position.clone().normalize();
  const side = new THREE.Vector3().crossVectors(outward, new THREE.Vector3(0, 1, 0));
  if (side.lengthSq() < 0.01) side.set(1, 0, 0);
  side.normalize();
  const end = start.clone().addScaledVector(outward, 1.0).addScaledVector(side, 0.58);
  const midpoint = start.clone().lerp(end, 0.5).addScaledVector(outward, 0.35);
  const curve = new THREE.QuadraticBezierCurve3(start, midpoint, end);
  const positions = link.line.geometry.getAttribute("position");
  for (let index = 0; index < positions.count; index += 1) {
    const point = curve.getPoint(index / (positions.count - 1));
    positions.setXYZ(index, point.x, point.y, point.z);
  }
  positions.needsUpdate = true;
  link.line.computeLineDistances();
  link.line.geometry.computeBoundingSphere();
  link.pulse.position.copy(curve.getPoint((observationPhase * 2.4) % 1));
  link.target.position.copy(end);
}

